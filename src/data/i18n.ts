export const DICTIONARIES: Record<Lang, Record<TranslationKey, string>> = { es, en };

/** Traduce una clave y sustituye los marcadores `{nombre}`. */
export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string | number>): string {
  let text: string = DICTIONARIES[lang][key] ?? DICTIONARIES.es[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
